#!/usr/bin/env python3
"""Generate the compact capability index solely from current authorities."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'docs/reference/current-capabilities.md'


def render(root=ROOT):
    release_path = 'packages/schema/capabilities/releases.json'
    registry_path = 'packages/schema/capabilities/registry.json'
    releases = json.loads((root / release_path).read_text())
    registry = json.loads((root / registry_path).read_text())
    rows = ['# Current capabilities', '',
            'Generated by `python3 tools/gvr-ops/current_capabilities.py`.',
            'Index only: status/scope remain owned by the linked registry and conformance.', '',
            '| Language | Current release | Wire |', '| --- | --- | --- |']
    for language, value in releases['languages'].items():
        rows.append(f"| {language} | {value['current']} | {value['wireVersion']} |")
    rows += ['', '| Capability | Compiler | Runtime | Renderer | Scope / evidence |',
             '| --- | --- | --- | --- | --- |']
    for capability in registry['capabilities']:
        support = capability.get('support', {})
        summary = capability.get('summary', '').replace('|', '\\|').replace('\n', ' ')
        evidence = capability.get('conformanceTests', [])
        link = f"[registry](../../{registry_path})"
        if evidence:
            file = evidence[0].split('#')[0]
            link += f'; [test](../../{file})'
        rows.append('| ' + ' | '.join([capability['id'],
                    *[support.get(target, 'not claimed') for target in ('compiler', 'runtime', 'renderer')],
                    summary + ' ' + link]) + ' |')
    rows += ['', 'Statuses are scoped claims, not an end-to-end visual certification. `untested`',
             'does not mean supported. Adapter `exact`/`approximate` scopes remain in the registry.',
             'Pending entries do not authorise invented syntax. Persistent semantic editing,',
             'general behaviours, input interaction, audible media, physics, 3D and real model',
             'generation are future work, not established by the native animation pipeline.', '',
             'See [grammar](../../packages/schema/src/grammar.ts),',
             '[compatibility](../languages/compatibility-policy.md),',
             '[evidence index](evidence-index.md) and [capacity decision](../design/capacity-transactions.md).',
             'P006/E006 own the later tested versioned model-facing syntax reference.', '',
             '## Input identity', '']
    for path in (release_path, registry_path):
        rows.append(f"- `{path}` SHA-256 `{hashlib.sha256((root/path).read_bytes()).hexdigest()}`")
    return '\n'.join(rows) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit('Capability index is stale; regenerate from current authorities.')
        print('Capability index matches current release/registry authorities.')
    else:
        OUTPUT.write_text(expected)
